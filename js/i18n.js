    const textSources = new WeakMap();
    const attributeSources = new WeakMap();
    let language = 'en';

    function translate(value) {
        const source = String(value);
        const exact = phraseTranslations[source.trim()];
        if (exact) {
            return exact;
        }

        const layyahNotice = source.match(/^Layyah arrangement submitted! Total: GHS ([\d,.]+)\. We will contact you for payment\.$/);
        if (layyahNotice) {
            return `تم إرسال طلب الأضحية. الإجمالي: ${layyahNotice[1]} سيدي غاني. سنتواصل معكم بشأن الدفع.`;
        }

        return source.replace(/[A-Za-z][A-Za-z'-]*/g, (word) => {
            const translated = wordTranslations[word.toLowerCase()];
            return translated || word;
        });
    }

    function translateNode(node) {
        if (!node || node.nodeType !== Node.TEXT_NODE || !node.textContent.trim()) {
            return;
        }
        if (!textSources.has(node)) {
            textSources.set(node, node.textContent);
        }
        const original = textSources.get(node);
        const leading = original.match(/^\s*/)[0];
        const trailing = original.match(/\s*$/)[0];
        const core = original.trim();
        const nextText = language === 'ar' ? `${leading}${translate(core)}${trailing}` : original;
        if (node.textContent !== nextText) {
            node.data = nextText;
        }
    }

    function translateAttributes(element) {
        if (!element || element.nodeType !== Node.ELEMENT_NODE) {
            return;
        }
        const attributes = ['placeholder', 'aria-label', 'title', 'alt'];
        attributes.forEach((name) => {
            if (!element.hasAttribute(name)) {
                return;
            }
            let sources = attributeSources.get(element);
            if (!sources) {
                sources = {};
                attributeSources.set(element, sources);
            }
            if (!(name in sources)) {
                sources[name] = element.getAttribute(name);
            }
            const original = sources[name];
            const nextValue = language === 'ar' ? translate(original) : original;
            if (element.getAttribute(name) !== nextValue) {
                element.setAttribute(name, nextValue);
            }
        });
        if (element.matches('input[type="submit"], input[type="button"]')) {
            let sources = attributeSources.get(element);
            if (!sources) {
                sources = {};
                attributeSources.set(element, sources);
            }
            if (!('value' in sources)) {
                sources.value = element.value;
            }
            const nextValue = language === 'ar' ? translate(sources.value) : sources.value;
            if (element.value !== nextValue) {
                element.value = nextValue;
            }
        }
    }

    function translateTree(root) {
        if (!root) {
            return;
        }
        if (root.nodeType === Node.TEXT_NODE) {
            translateNode(root);
            return;
        }
        if (root.nodeType === Node.ELEMENT_NODE) {
            if (root.matches('script, style, noscript')) {
                return;
            }
            translateAttributes(root);
            root.querySelectorAll('*').forEach(translateAttributes);
        }
        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
        while (walker.nextNode()) {
            const node = walker.currentNode;
            if (!node.parentElement.closest('script, style, noscript')) {
                translateNode(node);
            }
        }
    }

    function addSwitcher() {
        if (document.querySelector('.language-switcher')) {
            return;
        }
        const host = document.querySelector('.navbar-container') || document.querySelector('.topbar-actions');
        if (!host) {
            return;
        }
        const switcher = document.createElement('div');
        switcher.className = 'language-switcher';
        switcher.setAttribute('aria-label', 'Language selector');
        switcher.innerHTML = '<button type="button" class="lang-btn" data-language="en" aria-label="Switch to English">EN</button><button type="button" class="lang-btn" data-language="ar" aria-label="Switch to Arabic">عربي</button>';
        host.appendChild(switcher);
        switcher.addEventListener('click', (event) => {
            const button = event.target.closest('[data-language]');
            if (button) {
                setLanguage(button.dataset.language);
            }
        });
    }

    function setLanguage(nextLanguage) {
        language = nextLanguage === 'ar' ? 'ar' : 'en';
        window.localStorage.setItem(LANGUAGE_KEY, language);
        document.documentElement.lang = language;
        document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
        document.body.classList.toggle('rtl', language === 'ar');
        document.body.dir = language === 'ar' ? 'rtl' : 'ltr';
        document.body.dataset.language = language;

        const titleSource = document.documentElement.dataset.originalTitle || document.title;
        if (!document.documentElement.dataset.originalTitle) {
            document.documentElement.dataset.originalTitle = titleSource;
        }
        document.title = language === 'ar' ? translate(titleSource) : titleSource;

        document.querySelectorAll('.lang-btn').forEach((button) => {
            const active = button.dataset.language === language;
            button.classList.toggle('active', active);
            button.setAttribute('aria-pressed', String(active));
        });
        translateTree(document.body);
        document.querySelectorAll('option').forEach(translateNode);
        const description = document.querySelector('meta[name="description"]');
        if (description) {
            const original = description.dataset.originalDescription || description.content;
            if (!description.dataset.originalDescription) {
                description.dataset.originalDescription = original;
            }
            description.content = language === 'ar' ? translate(original) : original;
        }
    }

    function initialize() {
        addSwitcher();
        setLanguage(window.localStorage.getItem(LANGUAGE_KEY) || 'en');
        const observer = new MutationObserver((mutations) => {
            mutations.forEach((mutation) => {
                if (mutation.type === 'childList') {
                    mutation.addedNodes.forEach(translateTree);
                } else if (mutation.type === 'attributes') {
                    translateAttributes(mutation.target);
                }
            });
        });
        observer.observe(document.body, { childList: true, subtree: true, attributes: true, attributeFilter: ['placeholder', 'aria-label', 'title', 'alt', 'value'] });
    }

    window.KWTranslate = (value) => language === 'ar' ? translate(value) : String(value);
    window.KWI18n = { setLanguage, translate };

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', initialize, { once: true });
    } else {
        initialize();
    }
